package com.gojeom.common.enums;

/**
 * 프로필 사진을 <b>얼마나 읽을 수 있었는지</b>에 대한 AI의 자기 신고.
 * (④ 촬영 품질 게이트)
 *
 * <p><b>사진이나 사용자에게 등급을 매기는 값이 아니다.</b> 판독 조건이 충분했는지만
 * 말한다. {@code grade}·{@code score} 같은 이름을 쓰지 않는 이유가 여기 있다 —
 * 스키마의 필드 이름은 모델도 읽는다. 얼굴 정보 옆에 "등급" 칸을 두면 모델이 얼굴에
 * 등급을 매기기 시작한다. {@code JsonSchemasTest}가 그 이름들을 막고 있다. (PRD G-1)
 *
 * <p>이 값을 <b>화면에 그대로 내보내지 않는다.</b> 사용자는 자기가 평가받았다고 읽는다.
 * 프론트는 상태가 아니라 <b>무엇을 다시 하면 되는지</b>를 문장으로 말한다.
 */
public enum CaptureReadability {

    /** 세부까지 보였다. 안내를 띄우지 않는다. */
    CLEAR,

    /** 일부가 확실하지 않다. 다시 찍으면 나아진다고 알린다. */
    PARTIAL,

    /** 제대로 보기 어려웠다. 다시 찍기를 권한다. */
    LIMITED
}
