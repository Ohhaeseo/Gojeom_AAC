package com.gojeom.common.enums;

/**
 * 프로필 사진 판독을 방해한 요인. (④ 촬영 품질 게이트)
 *
 * <p><b>자유 서술이 아니라 열거형인 것이 요점이다.</b> AI에게 문장을 짓게 하면
 * 사용자에게 노출되는 새 텍스트가 생겨 가드레일 검사 대상이 하나 늘어난다.
 * AI는 <b>분류만</b> 하고, 사용자에게 할 말은 프론트가 이 값으로 고른다.
 *
 * <p>값을 추가하면 프론트의 문구 표({@code captureNotice})도 함께 늘려야 한다.
 * 매핑이 없는 값은 안내에서 조용히 빠진다.
 */
public enum CaptureIssue {

    /** 전반적으로 어둡다. */
    DARK,

    /** 역광이라 얼굴만 어둡다. */
    BACKLIT,

    /** 흔들렸거나 초점이 맞지 않는다. */
    BLURRY,

    /** 얼굴이 작게 담겨 피부 결까지 보이지 않는다. */
    FACE_TOO_SMALL,

    /** 머리카락·마스크·안경 등에 얼굴 일부가 가렸다. */
    OCCLUDED,

    /** 보정이 강해 실제 피부 상태와 다르게 보인다. */
    HEAVY_FILTER,

    /** 사람이 여럿이라 누구를 봐야 할지 정할 수 없다. */
    MULTIPLE_FACES,

    /** 얼굴을 찾지 못했다. */
    NO_FACE
}
